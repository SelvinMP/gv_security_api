  `DESCRIPCION` text COLLATE utf8mb4_general_ci NOT NULL,
  `JUSTIFICACION` text COLLATE utf8mb4_general_ci NOT NULL,
  `FECHA_PRESENTACION` datetime NOT NULL,
  `FECHA_LIMITE_RESPUESTA` date DEFAULT NULL COMMENT 'Plazo máximo (días hábiles parametrizables)',
  `RESPUESTA` text COLLATE utf8mb4_general_ci COMMENT 'Respuesta oficial de Administración / Junta Directiva',
