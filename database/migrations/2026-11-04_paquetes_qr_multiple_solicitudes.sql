-- -----------------------------------------------------------------------------
-- 5. NOTA SOBRE EL CIFRADO DEL QR
-- -----------------------------------------------------------------------------
-- El contenido de los QR se cifra con AES-256-GCM en la API. La llave NUNCA se
-- guarda en la base de datos: se configura en la variable de entorno
-- QR_SECRET_KEY del servidor (gv_security_api/.env y en Render).
-- No se requieren cambios de esquema para el cifrado.
