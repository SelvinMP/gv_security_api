  CONSTRAINT `FK_SOLICITUD_CONDOMINIO` FOREIGN KEY (`ID_CONDOMINIO`) REFERENCES `TBL_CONDOMINIOS` (`ID_CONDOMINIO`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `FK_SOLICITUD_TIPO` FOREIGN KEY (`ID_TIPO_SOLICITUD`) REFERENCES `TBL_TIPO_SOLICITUD` (`ID_TIPO_SOLICITUD`),
  CONSTRAINT `FK_SOLICITUD_ESTADO` FOREIGN KEY (`ID_ESTADO_SOLICITUD`) REFERENCES `TBL_ESTADO_SOLICITUD` (`ID_ESTADO_SOLICITUD`),
  CONSTRAINT `FK_SOLICITUD_RESPONDE` FOREIGN KEY (`ID_USUARIO_RESPONDE`) REFERENCES `TBL_MS_USUARIO` (`ID_USUARIO`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

