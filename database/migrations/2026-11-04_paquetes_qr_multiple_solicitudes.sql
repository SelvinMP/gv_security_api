-- Paquetes autorizados por el residente (un QR único por paquete).
CREATE TABLE IF NOT EXISTS `TBL_PAQUETES` (
  `ID_PAQUETE` int NOT NULL AUTO_INCREMENT,
  `ID_USUARIO` int NOT NULL COMMENT 'Residente que autoriza el paquete',
  `ID_PERSONA` int DEFAULT NULL,
  `ID_CONDOMINIO` int DEFAULT NULL COMMENT 'Número de casa destino',
  `REMITENTE` varchar(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT 'Empresa o persona que envía (Amazon, Temu, familiar...)',
  `TIPO_REMITENTE` varchar(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL DEFAULT 'EMPRESA' COMMENT 'EMPRESA | FAMILIAR | AMIGO',
  `ID_TAMANO_PAQUETE` int NOT NULL,
  `FECHA_ESTIMADA_ENTREGA` date NOT NULL,
  `DESCRIPCION` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT 'Nota del residente',
  `ESTADO_QR` tinyint DEFAULT '0' COMMENT '0 = Pendiente, 1 = Recibido en caseta',
  `FECHA_HORA` datetime NOT NULL COMMENT 'Fecha de creación del QR',
  `FECHA_MODIFICACION` datetime DEFAULT NULL,
  `FECHA_RECEPCION` datetime DEFAULT NULL,
  `ID_USUARIO_GUARDIA` int DEFAULT NULL COMMENT 'Guardia que recibió el paquete',
  `ID_GEOCERCA` int DEFAULT NULL,
  `ESTADO_PAQUETE` varchar(30) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT 'INTACTO | ROTO | APLASTADO | MOJADO | ABIERTO | OTRO',
  `OBSERVACIONES_GUARDIA` text COLLATE utf8mb4_general_ci,
  `LATITUD_ESCANEO` decimal(10,8) DEFAULT NULL,
  `LONGITUD_ESCANEO` decimal(11,8) DEFAULT NULL,
  PRIMARY KEY (`ID_PAQUETE`),
  KEY `FK_PAQUETE_USUARIO_idx` (`ID_USUARIO`),
  KEY `FK_PAQUETE_CONDOMINIO_idx` (`ID_CONDOMINIO`),
  KEY `FK_PAQUETE_TAMANO_idx` (`ID_TAMANO_PAQUETE`),
  KEY `FK_PAQUETE_GUARDIA_idx` (`ID_USUARIO_GUARDIA`),
  KEY `IDX_PAQUETE_FECHA` (`FECHA_RECEPCION`),
  CONSTRAINT `FK_PAQUETE_USUARIO` FOREIGN KEY (`ID_USUARIO`) REFERENCES `TBL_MS_USUARIO` (`ID_USUARIO`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `FK_PAQUETE_CONDOMINIO` FOREIGN KEY (`ID_CONDOMINIO`) REFERENCES `TBL_CONDOMINIOS` (`ID_CONDOMINIO`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `FK_PAQUETE_TAMANO` FOREIGN KEY (`ID_TAMANO_PAQUETE`) REFERENCES `TBL_TAMANO_PAQUETE` (`ID_TAMANO_PAQUETE`),
  CONSTRAINT `FK_PAQUETE_GUARDIA` FOREIGN KEY (`ID_USUARIO_GUARDIA`) REFERENCES `TBL_MS_USUARIO` (`ID_USUARIO`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `FK_PAQUETE_GEOCERCA` FOREIGN KEY (`ID_GEOCERCA`) REFERENCES `TBL_GEOCERCAS` (`ID_GEOCERCA`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

