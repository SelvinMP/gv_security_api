CREATE TABLE IF NOT EXISTS `TBL_TIPO_SOLICITUD` (
  `ID_TIPO_SOLICITUD` int NOT NULL AUTO_INCREMENT,
  `DESCRIPCION` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL,
  `DETALLE` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL,
  PRIMARY KEY (`ID_TIPO_SOLICITUD`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

INSERT INTO `TBL_TIPO_SOLICITUD` (`DESCRIPCION`, `DETALLE`)
SELECT * FROM (
  SELECT 'QUEJA' AS d, 'Inconformidad sobre un servicio, vecino o situación' AS t UNION ALL
  SELECT 'SUGERENCIA', 'Propuesta de mejora para la comunidad' UNION ALL
  SELECT 'ADMINISTRATIVA', 'Mantenimiento, seguridad, servicios comunes' UNION ALL
  SELECT 'NORMATIVA', 'Cambios o propuestas al reglamento interno de Villa las Acacias' UNION ALL
  SELECT 'COMUNITARIA', 'Actividades sociales, culturales o de convivencia' UNION ALL
  SELECT 'EXCEPCIONAL', 'Casos urgentes o especiales: autorización de taxis/Uber para tercera edad, enfermos'
) AS nuevos
WHERE NOT EXISTS (SELECT 1 FROM `TBL_TIPO_SOLICITUD` ts WHERE ts.`DESCRIPCION` = nuevos.d);

CREATE TABLE IF NOT EXISTS `TBL_ESTADO_SOLICITUD` (
  `ID_ESTADO_SOLICITUD` int NOT NULL AUTO_INCREMENT,
  `DESCRIPCION` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL,
  PRIMARY KEY (`ID_ESTADO_SOLICITUD`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

INSERT INTO `TBL_ESTADO_SOLICITUD` (`ID_ESTADO_SOLICITUD`, `DESCRIPCION`)
SELECT * FROM (
  SELECT 1 AS i, 'RECIBIDA' AS d UNION ALL
  SELECT 2, 'EN REVISIÓN' UNION ALL
  SELECT 3, 'REQUIERE INFORMACIÓN' UNION ALL
  SELECT 4, 'APROBADA' UNION ALL
  SELECT 5, 'RECHAZADA' UNION ALL
  SELECT 6, 'CERRADA'
) AS nuevos
WHERE NOT EXISTS (SELECT 1 FROM `TBL_ESTADO_SOLICITUD` es WHERE es.`ID_ESTADO_SOLICITUD` = nuevos.i);

CREATE TABLE IF NOT EXISTS `TBL_SOLICITUDES` (
  `ID_SOLICITUD` int NOT NULL AUTO_INCREMENT,
  `NUM_SEGUIMIENTO` varchar(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT 'Ej: SOL-2026-000001',
