WHERE NOT EXISTS (SELECT 1 FROM `TBL_TAMANO_PAQUETE` WHERE `DESCRIPCION` = 'PEQUEÑO');
INSERT INTO `TBL_TAMANO_PAQUETE` (`DESCRIPCION`, `DIMENSIONES_MAXIMAS`, `PERMITIDO`)
SELECT 'MEDIANO', 'Hasta 60 x 45 x 45 cm / 15 kg', 1 FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM `TBL_TAMANO_PAQUETE` WHERE `DESCRIPCION` = 'MEDIANO');
