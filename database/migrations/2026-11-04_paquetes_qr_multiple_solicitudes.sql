-- Catálogo de tamaños de paquete definidos por la administración.
-- PERMITIDO = 1 → el guardia puede recibirlo en caseta.
CREATE TABLE IF NOT EXISTS `TBL_TAMANO_PAQUETE` (
  `ID_TAMANO_PAQUETE` int NOT NULL AUTO_INCREMENT,
  `DESCRIPCION` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL,
  `DIMENSIONES_MAXIMAS` varchar(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT 'Ej: Hasta 30 x 30 x 30 cm',
  `PERMITIDO` tinyint(1) NOT NULL DEFAULT '1' COMMENT '1 = Se recibe en caseta, 0 = No se recibe',
  PRIMARY KEY (`ID_TAMANO_PAQUETE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

INSERT INTO `TBL_TAMANO_PAQUETE` (`DESCRIPCION`, `DIMENSIONES_MAXIMAS`, `PERMITIDO`)
