  `ID_TIPO_SOLICITUD` int NOT NULL,
  `ID_ESTADO_SOLICITUD` int NOT NULL DEFAULT '1',
  `CANAL` varchar(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL DEFAULT 'PLATAFORMA' COMMENT 'PLATAFORMA | CORREO | FISICO',
