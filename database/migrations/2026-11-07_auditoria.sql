--  Las tablas TBL_LOG_* se llenaban con triggers de la base anterior (Hostinger),
--  que no se migraron a Railway; desde marzo 2026 no se registraba nada.
--
--  1) Agrega ACCION y DETALLE a las tablas de log (usuarios, personas, parámetros,
--     roles, permisos e historial de contraseñas). La API registra los eventos.
--  2) Crea triggers para TBL_MS_ROLES y TBL_PERMISOS, que solo se modifican
--     directamente en la base de datos (no tienen pantalla en la app).
--
--  La API aplica esto automáticamente al arrancar (src/config/ensureSchema.js).
--  Este script es para aplicarlo a mano si se prefiere. Idempotente.
--    mysql -h <HOST_DB> -P <PUERTO> -u <USUARIO> -p railway < 2026-11-07_auditoria.sql
-- =============================================================================

SET NAMES utf8mb4;

DROP PROCEDURE IF EXISTS `GV_ADD_COLUMN_IF_MISSING`;
DELIMITER $$
CREATE PROCEDURE `GV_ADD_COLUMN_IF_MISSING`(IN p_table VARCHAR(64), IN p_column VARCHAR(64), IN p_definition VARCHAR(255))
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.COLUMNS
     WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = p_table AND COLUMN_NAME = p_column
  ) THEN
    SET @ddl = CONCAT('ALTER TABLE `', p_table, '` ADD COLUMN `', p_column, '` ', p_definition);
    PREPARE stmt FROM @ddl;
    EXECUTE stmt;
    DEALLOCATE PREPARE stmt;
  END IF;
END$$
DELIMITER ;

